// Renders the 5 ads defined in ads/ads.ts at 1080x1350 and 1080x1080 from
// ads/templates/ad.html, then rewrites ads/COPY.md from the same data.
// Business name, phone, commission wording and service promises come from src/config/site.ts.
import { chromium } from 'playwright';
import { readFileSync, writeFileSync, unlinkSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { ads, brand } from '../ads/ads';
import { site } from '../src/config/site';

const dir = resolve('ads/templates');
const out = resolve('ads');
const sizes = [
  { w: 1080, h: 1350, cls: '' },
  { w: 1080, h: 1080, cls: 'sq' },
];
const esc = (s: string) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
const tpl = readFileSync(join(dir, 'ad.html'), 'utf8');
const executablePath = process.env.CHROME_PATH || '/usr/bin/google-chrome';
const browser = await chromium.launch({ executablePath });
for (const ad of ads) {
  for (const s of sizes) {
    const html = tpl
      .replaceAll('{{SIZE}}', s.cls)
      .replaceAll('{{FLAGSHIP}}', ad.flagship ? 'flagship' : '')
      .replaceAll('{{POS}}', ad.pos)
      .replaceAll('{{IMAGE}}', ad.image)
      .replaceAll('{{BADGE}}', esc(ad.badge))
      .replaceAll('{{EYEBROW}}', esc(ad.eyebrow))
      .replaceAll('{{HEADLINE}}', esc(ad.onImage))
      .replaceAll('{{CTA}}', esc(ad.cta))
      .replaceAll('{{BUSINESS}}', esc(brand.name))
      .replaceAll('{{PHONE}}', esc(brand.phone));
    const tmp = join(dir, `_render-${ad.slug}.html`);
    writeFileSync(tmp, html);
    const page = await browser.newPage({ viewport: { width: s.w, height: s.h }, deviceScaleFactor: 1 });
    await page.goto('file://' + tmp);
    await page.evaluate(() => document.fonts.ready);
    const file = join(out, `${ad.slug}-${s.w}x${s.h}.png`);
    await page.screenshot({ path: file });
    await page.close();
    unlinkSync(tmp);
    console.log(file);
  }
}
await browser.close();

const md = [
  '# Ad copy',
  '',
  '<!-- GENERATED by `npm run ads` from ads/ads.ts and src/config/site.ts. Edit those, not this file. -->',
  '',
  `Five ads for ${site.businessName}, each in 1080x1350 (feed, 4:5) and 1080x1080 (square). Ad 1, the full house buyout, is the flagship.`,
  `The phone number on every image (${site.phoneDisplay}) is a PLACEHOLDER from \`src/config/site.ts\`. Re-run \`npm run ads\` once the real number is set.`,
  'Service promises (keepsakes, donations, broom-clean, executor summary, reply time) come from the `servicePromises` block in `src/config/site.ts`, which is UNCONFIRMED by Azmat. Cut one there and it drops out of this copy.',
  '',
  'All copy is plain, calm and truthful: no prices, no stats, no reviews, no urgency tricks.',
  '',
  ...ads.flatMap((ad, i) => [
    `## ${i + 1}. ${ad.audience}`,
    `Files: \`${ad.slug}-1080x1350.png\`, \`${ad.slug}-1080x1080.png\``,
    `- On image: "${ad.onImage}" CTA: ${ad.cta}`,
    `- Headline: ${ad.headline}`,
    `- Primary text: ${ad.primary}`,
    '',
  ]),
].join('\n');
writeFileSync(join(out, 'COPY.md'), md);
console.log(join(out, 'COPY.md'));
